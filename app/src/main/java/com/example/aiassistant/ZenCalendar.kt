    fun today(): DayInfo {
        val cal = java.util.Calendar.getInstance()
        return infoAt(
            cal.get(java.util.Calendar.YEAR),
            cal.get(java.util.Calendar.MONTH) + 1,
            cal.get(java.util.Calendar.DAY_OF_MONTH)
        )
    }

    /** 指定公历日期的显示信息。包内可见以便单测。 */
    internal fun infoAt(year: Int, month: Int, day: Int): DayInfo {
        val days = termDays(year)
        // 找"最近已开始"的节气：小寒之前落空则取上一年冬至
        var termIdx = -1
        for (i in TERM_NAMES.indices) {
            val termMonth = i / 2 + 1
            val termDay = days[i]
            if (month > termMonth || (month == termMonth && day >= termDay)) termIdx = i
        }
        if (termIdx < 0) {
            // 小寒（1月5/6日）之前：当前节气仍是上一年冬至（12月21/22日横跨元旦）
            val yearName = ganzhi(year - 1)
            return DayInfo(yearName, TERM_NAMES[23], "宜 ‖ ${TERM_SUIT[23]}")
        }
        // 干支纪年以立春（index 2）为界
        val lichunMonth = 2
        val lichunDay = days[2]
        val gzYear = if (month > lichunMonth || (month == lichunMonth && day >= lichunDay)) year else year - 1
        return DayInfo(ganzhi(gzYear), TERM_NAMES[termIdx], "宜 ‖ ${TERM_SUIT[termIdx]}")
    }

    /** 每年 24 节气的"日"数组：表内有权威值，表外用通式公式估算 */
    private fun termDays(year: Int): IntArray {
        val enc = TERM_DAYS[year]
        if (enc != null) {
            return IntArray(24) { i ->
                val s = enc.substring(i * 2, i * 2 + 2)
                s.toInt()
            }
        }
        val y = year % 100
        return IntArray(24) { i ->
            val l = if (i < 4) (y - 1) / 4 else y / 4
            (y * 0.2422 + TERM_C[i] - l).toInt()
        }
    }

    private fun ganzhi(year: Int): String {
        val stem = STEMS[((year - 4) % 10 + 10) % 10]
        val branch = BRANCHES[((year - 4) % 12 + 12) % 12]
        return "${stem}${branch}年"
    }
